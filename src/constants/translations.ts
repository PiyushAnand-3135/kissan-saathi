export type TranslationKey = keyof typeof translations.en;

export function getCropTranslationKey(nameOrId: string): TranslationKey {
  const key = (nameOrId || '').toLowerCase();
  if (key.includes('wheat') || key.includes('गेहूं') || key.includes('गहू') || key.includes('গম')) return 'cropWheat';
  if (key.includes('soybean') || key.includes('सोयाबीन') || key.includes('সয়াবিন')) return 'cropSoybean';
  if (key.includes('cotton') || key.includes('कपास') || key.includes('कापूस') || key.includes('তুলা')) return 'cropCotton';
  if (key.includes('paddy') || key.includes('rice') || key.includes('धान') || key.includes('भात')) return 'cropPaddy';
  if (key.includes('mustard') || key.includes('सरसों') || key.includes('मोहरी') || key.includes('সরিষা')) return 'cropMustard';
  if (key.includes('maize') || key.includes('corn') || key.includes('मक्का') || key.includes('मका') || key.includes('ভুট্টা')) return 'cropMaize';
  return 'cropWheat';
}

export function getVehicleTranslationKey(vehicle: string): TranslationKey {
  const v = (vehicle || '').toLowerCase();
  if (v.includes('tractor') || v.includes('ट्रैक्टर') || v.includes('ट्रॅक्टर') || v.includes('ট্রাক্টর')) return 'tractorTrolley';
  if (v.includes('truck') || v.includes('ट्रक') || v.includes('ট্রাক')) return 'smallTruck';
  if (v.includes('pickup') || v.includes('पिकअप') || v.includes('bolero') || v.includes('ভ্যান')) return 'boleroPickup';
  return 'tractorTrolley';
}
